"""Repository policy: fixture records, golden coverage, and provenance.

These are the rules no single artifact test can own. A golden test proves one
artifact is right; nothing here inspects a generated byte. What is checked is
that every case has a record, that every record carries the same shape, that
every golden is named by the record that explains it, and that no name from the
architecture this repository was ported from survives into the sources or the
goldens.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from conftest import FIXTURE_ROOT, GOLDEN_ROOT

pytestmark = pytest.mark.static

SUBJECTS = ("bus", "controller", "generator", "minimal", "packages", "sensor")

CASE_HEADINGS = (
    "# Case:",
    "## Artifacts",
    "## What this case proves",
    "## Update history",
)

CASE_FIELDS = (
    "Conversion",
    "Requirement / fault",
    "Level",
    "Input",
    "Expected",
    "Independent oracle",
    "Comparison",
    "Normalization",
    "Volatile fields",
    "Update policy",
    "Notes",
)

#: Names from the architecture the fixtures were ported from. None may reach a
#: generated artifact, and none may reach the sources.
FORBIDDEN_NAMES = (
    "Aircraft",
    "AircraftCommon",
    "FlightGearBridge",
    "FuelSystem",
    "MissionComputer",
)

#: A case record may *document* a removed name; a golden may not *contain* one.
#: Keyed by path relative to the repository, valued by the names it may mention.
#: Empty on purpose: provenance is described, never quoted by name.
PROVENANCE_MENTIONS: dict[str, tuple[str, ...]] = {}

#: ``doc /* ... */`` blocks, whose lines are capped by ``fixtures/README.md``.
DOC_BLOCK = re.compile(r"/\*.*?\*/", re.DOTALL)

#: The most inline documentation a fixture may carry, in lines.
DOC_LINE_LIMIT = 15

REPO_ROOT = Path(__file__).resolve().parent.parent

#: The package root the layering rules also guard.
SRC_ROOT = REPO_ROOT / "src"

TEXT_SUFFIXES = {
    ".h",
    ".md",
    ".mo",
    ".order",
    ".py",
    ".sysml",
    ".toml",
    ".txt",
    ".xml",
}


def _relative(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def _case_records(root: Path) -> list[Path]:
    """Every ``case.md`` below ``root``, in path order."""
    return sorted(root.rglob("case.md"))


def _text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _mentions_field(text: str, label: str) -> bool:
    """Whether ``text`` carries ``label`` as ``**Label:**``, ``**Label**:`` or ``Label:``."""
    bold = re.compile(rf"\*\*{re.escape(label)}:?\*\*")
    plain = re.compile(rf"(?m)^{re.escape(label)}:")
    return bool(bold.search(text) or plain.search(text))


def _governing_case(path: Path) -> Path | None:
    """The nearest ``case.md`` in ``path``'s directory or above, inside ``tests``."""
    for directory in path.parents:
        if directory == REPO_ROOT:
            return None
        candidate = directory / "case.md"
        if candidate.is_file():
            return candidate
    return None


def _artifact_files(root: Path) -> list[Path]:
    """Every non-record file below ``root``."""
    return sorted(p for p in root.rglob("*") if p.is_file() and p.name != "case.md")


def _text_files(root: Path) -> list[Path]:
    """Every text file below ``root``; binaries are skipped by suffix."""
    return sorted(p for p in root.rglob("*") if p.is_file() and p.suffix in TEXT_SUFFIXES)


# --------------------------------------------------------------------------- records


def test_every_fixture_directory_has_a_record():
    directories = sorted(p for p in FIXTURE_ROOT.iterdir() if p.is_dir())
    assert [p.name for p in directories] == list(SUBJECTS), (
        "the fixture set changed; document the new subject in tests/fixtures/README.md"
    )
    missing = [
        _relative(d) for d in directories if not (d / "case.md").is_file()
    ]
    assert not missing, f"fixture directories without case.md: {missing}"


def test_every_fixture_has_a_file_named_after_its_directory():
    wrong = [
        _relative(d)
        for d in sorted(p for p in FIXTURE_ROOT.iterdir() if p.is_dir())
        if not (d / f"{d.name}.sysml").is_file()
    ]
    assert not wrong, f"fixture directories without <subject>.sysml: {wrong}"


def test_every_golden_case_has_a_record():
    """A case record may sit above an artifact directory (``Scale/modelDescription.xml``)."""
    subjects = sorted(p for p in GOLDEN_ROOT.iterdir() if p.is_dir())
    assert subjects, "no golden subject directories"
    unrecorded = [
        _relative(p) for p in subjects if not any(p.rglob("case.md"))
    ]
    assert not unrecorded, f"golden subjects without any case.md: {unrecorded}"

    orphans = [
        _relative(p)
        for p in _artifact_files(GOLDEN_ROOT)
        if _governing_case(p) is None
    ]
    assert not orphans, f"golden artifacts with no case.md at or above them: {orphans}"


def test_case_records_start_with_the_case_heading():
    wrong = [
        _relative(p)
        for p in _case_records(FIXTURE_ROOT) + _case_records(GOLDEN_ROOT)
        if not _text(p).lstrip().startswith("# Case:")
    ]
    assert not wrong, f"case.md not starting with '# Case:': {wrong}"


def test_case_records_have_the_four_headings_in_order():
    wrong: list[str] = []
    for path in _case_records(FIXTURE_ROOT) + _case_records(GOLDEN_ROOT):
        text = _text(path)
        positions = [text.find(heading) for heading in CASE_HEADINGS]
        if -1 in positions or positions != sorted(positions):
            wrong.append(f"{_relative(path)} {dict(zip(CASE_HEADINGS, positions))}")
    assert not wrong, "case.md with missing or out-of-order headings: " + "; ".join(wrong)


def test_case_records_name_all_eleven_fields():
    wrong: list[str] = []
    for path in _case_records(FIXTURE_ROOT) + _case_records(GOLDEN_ROOT):
        text = _text(path)
        missing = [label for label in CASE_FIELDS if not _mentions_field(text, label)]
        if missing:
            wrong.append(f"{_relative(path)} missing {missing}")
    assert not wrong, "case.md with missing fields: " + "; ".join(wrong)


def test_fixture_records_state_their_provenance():
    wrong: list[str] = []
    for path in _case_records(FIXTURE_ROOT):
        text = _text(path)
        if not re.search(r"(?m)^\*\*Provenance\*\*: .*\S", text):
            wrong.append(_relative(path))
    assert not wrong, f"fixture records without a provenance line: {wrong}"


# --------------------------------------------------------------------------- goldens


def test_every_golden_artifact_is_named_in_its_case_record():
    """Each golden must be reachable from its record by a backticked relative path."""
    missing: list[str] = []
    for path in _artifact_files(GOLDEN_ROOT):
        case = _governing_case(path)
        assert case is not None, _relative(path)
        text = _text(case)
        subject = path.relative_to(GOLDEN_ROOT).parts[0]
        candidates = {
            path.relative_to(case.parent).as_posix(),
            path.relative_to(GOLDEN_ROOT / subject).as_posix(),
            path.parent.relative_to(case.parent).as_posix(),
        }
        if any(f"`{candidate}`" in text for candidate in candidates):
            continue
        missing.append(f"{_relative(path)} not named in {_relative(case)}")
    assert not missing, "undocumented goldens: " + "; ".join(missing)


# --------------------------------------------------------------------------- provenance


def test_no_source_architecture_name_survives():
    """No ported name may appear in the sources or in a golden artifact."""
    hits: list[str] = []
    for path in _text_files(SRC_ROOT) + _text_files(GOLDEN_ROOT):
        allowed = PROVENANCE_MENTIONS.get(_relative(path), ())
        for number, line in enumerate(_text(path).splitlines(), start=1):
            found = [name for name in FORBIDDEN_NAMES if name in line]
            # ``AircraftCommon`` implies ``Aircraft``; report the longest match only.
            found = [
                name
                for name in found
                if not any(name != other and name in other for other in found)
            ]
            unexpected = [name for name in found if name not in allowed]
            if unexpected:
                hits.append(f"{_relative(path)}:{number}: {unexpected}")
    assert not hits, "ported architecture names leaked: " + "; ".join(hits)


# --------------------------------------------------------------------------- fixtures


def test_no_test_reads_a_fixture_by_a_working_directory_relative_path():
    """Fixture reads go through ``conftest.fixture_path``; cwd is not a contract."""
    offenders = [
        _relative(p)
        for p in _text_files(GOLDEN_ROOT.parent)
        if p.suffix == ".py"
        and re.search(r"Path\(\s*[\"']tests/", _text(p)) is not None
    ]
    assert not offenders, f"cwd-relative fixture paths in: {offenders}"


def test_fixture_inline_documentation_stays_within_the_limit():
    over = []
    for path in sorted(FIXTURE_ROOT.rglob("*.sysml")):
        lines = sum(
            block.count("\n") + 1 for block in DOC_BLOCK.findall(_text(path))
        )
        if lines > DOC_LINE_LIMIT:
            over.append(f"{_relative(path)}: {lines} lines")
    assert not over, (
        f"fixtures over the {DOC_LINE_LIMIT}-line inline-documentation limit: {over}"
    )
